def seed() -> None:
    conn = db.get_conn()
    try:
        if conn.execute("SELECT COUNT(*) c FROM cavities").fetchone()["c"]:
            return  # 已播种，幂等返回
        random.seed(20260901)
        now = int(time.time() * 1000)

        # ---- 空洞 ----
        for i, c in enumerate(_CAVITIES, 1):
            (road, dist, loc, vel, area, leak, vol, depth,
             status, found, remark) = c
            score, level = calc_cavity_risk(area, leak, vol)
            conn.execute(
                "INSERT INTO cavities(code,road_name,district,location,radar_velocity,"
                "radar_area,leakage_index,cavity_volume,depth_m,risk_score,risk_level,"
                "status,found_at,remark,created_ts) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                (f"KD-2026-{i:03d}", road, dist, loc, vel, area, leak, vol, depth,
                 score, level, status, found, remark, now))

        # ---- 沉降 ----
        for code, road, dist, deltas, source in _SUBS_POINTS:
            cum = 0.0
            for k, d in enumerate(deltas):
                cum = round(cum + d, 1)
                conn.execute(
                    "INSERT INTO subsidence_records(point_code,road_name,district,"
                    "measured_at,delta_mm,cumulative_mm,source,created_ts)"
                    " VALUES(?,?,?,?,?,?,?,?)",
                    (code, road, dist, _MEASURE_DATES[k], d, cum, source, now))

        # ---- 施工评估 ----
        for i, c in enumerate(_CONSTRUCTIONS, 1):
            (proj, unit, road, dist, wtype, depth, dpipe,
             start, days, measures, assessor) = c
            soil, pipe, overall, level = calc_construction_risk(wtype, depth, dpipe)
            conn.execute(
                "INSERT INTO construction_assess(project_name,construction_unit,road_name,"
                "district,work_type,excavation_depth,distance_to_pipe,start_date,plan_days,"
                "soil_score,pipe_score,overall_score,risk_level,measures,assessor,"
                "assessed_at,created_ts) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                (proj, unit, road, dist, wtype, depth, dpipe, start, days,
                 soil, pipe, overall, level, measures, assessor, "2026-08-28", now))

        conn.commit()
    finally:
        conn.close()
