def _node(seq, node_type, title, desc, deadline_min, responsible, resources, actions, exit_condition):
    return {
        "node_id": "FN-%02d" % seq,
        "seq": seq,
        "node_type": node_type,
        "title": title,
        "desc": desc,
        "deadline_min": deadline_min,
        "responsible": responsible,
        "resources": resources,
        "actions": actions,
        "exit_condition": exit_condition,
    }


def _resp(org, role, contact, cooperators=None):
    return {"org": org, "role": role, "contact": contact, "cooperators": cooperators or []}


def _res(rtype, name, quantity, unit, location):
    return {"resource_type": rtype, "name": name, "quantity": quantity, "unit": unit, "location": location}


def _act(action, detail, auto=False):
    return {"action": action, "detail": detail, "auto": auto}


def _plan(plan_id, plan_name, category, level_min, level_max, priority, status,
          scope_cabins, scope_zones, objective, commander, tags, flow_nodes,
          created_days_ago, updated_days_ago, version_note="一期种子版本"):
    now = datetime.now()
    return {
        "plan_id": plan_id,
        "plan_name": plan_name,
        "category": category,
        "level_min": level_min,
        "level_max": level_max,
        "priority": priority,
        "status": status,
        "scope_cabins": scope_cabins,
        "scope_zones": scope_zones,
        "objective": objective,
        "commander": commander,
        "tags": tags,
        "version_note": version_note,
        "flow_nodes": flow_nodes,
        "created_at": (now - timedelta(days=created_days_ago)).strftime("%Y-%m-%d %H:%M:%S"),
        "updated_at": (now - timedelta(days=updated_days_ago)).strftime("%Y-%m-%d %H:%M:%S"),
    }


